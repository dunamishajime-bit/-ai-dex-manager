#!/usr/bin/env python3
"""Read-only proof of exact-venue history availability for Q102.
A historical economic performance result is NOT generated by this tool.
"""
from datetime import datetime,timezone,timedelta
from pathlib import Path
import json
import hashlib
ROOT=Path(__file__).resolve().parents[2]
EVIDENCE=ROOT/"docs/research/evidence/Q102_ASTER_NATIVE_H1_EARLIEST_23_SYMBOLS_20261028.json"
TARGET_START=datetime(2025,8,10,tzinfo=timezone.utc)
HISTORY_START=TARGET_START-timedelta(days=181)
def validate():
 raw=EVIDENCE.read_bytes()
 source=json.loads(raw)
 assert source["queryStartUtc"]=="2025-02-10T00:00:00Z"
 assert source["limit"]==1
 rows=source["results"]
 assert len(rows)==23 and len({r["symbol"] for r in rows})==23
 limit=int(HISTORY_START.timestamp()*1000)
 missing=[dict(symbol=r["symbol"],firstAsterUtc=r["earliestReturnUtc"])
          for r in rows if r["earliestReturnTs"] is None or r["earliestReturnTs"]>limit]
 complete=[r["symbol"] for r in rows if r["earliestReturnTs"] is not None and r["earliestReturnTs"]<=limit]
 earliest_all=max(r["earliestReturnTs"] for r in rows)
 earliest_possible=datetime.fromtimestamp(earliest_all/1000,timezone.utc)+timedelta(days=181)
 # Even first-bar timestamps never prove gap-free warmup; the latter requires
 # verified hourly coverage (complete candles, hashes, and source provenance).
 return {
  "schema":"disdex-q102-aster-native-annual-coverage-gate/v1",
  "status":"BLOCKED_MISSING_NATIVE_181DAY_WARMUP" if missing else "EARLIEST_TIMESTAMP_GATE_ONLY",
  "targetYearUtc":"2025-08-10 through 2026-08-10",
  "requiredNativeWarmupStartsUtc":HISTORY_START.isoformat(),
  "sourceReadOnly":True,"tradingOrdersSent":0,
  "sourceSha256":hashlib.sha256(raw).hexdigest(),
  "symbolsChecked":len(rows),"missingWarmupCount":len(missing),
  "missingWarmupSymbols":missing,"otherSymbolsPassingEarliestTimestampOnly":complete,
  "earliestPossibleAll23Utc":earliest_possible.isoformat(),
  "furtherGates":["Verify continuous 1h Aster bar coverage from warmup through end","Verify per-symbol symbol listing and native contract","Recompute exact current Q102 SHA and ALL eight runners under same priority/Gross 10/30bps","Preserve historical signed venue provenance; never substitute other venue data"],
  "annualEconomicBTCertified":False
 }
if __name__=="__main__":
 print(json.dumps(validate(),ensure_ascii=False,sort_keys=True,indent=2))
 raise SystemExit(2 if validate()["missingWarmupCount"] else 0)
