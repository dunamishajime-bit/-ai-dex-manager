import assert from "node:assert/strict";
import { evaluateQ102HighVolD126 } from "../lib/disdex-quality102-highvol-d126";
import { quality102GrossForFamily } from "../config/integratedProductionRiskPolicy";
const H=3_600_000;
const t=Date.UTC(2026, 8, 17, 8);
const bars=Array.from({length:49},(_,i)=>({ timestampMs:t-(49-i)*H, close:100+i }));
const expected=evaluateQ102HighVolD126(bars,t);
assert.equal(expected.status,"LONG_OVERRIDE");
assert.deepEqual(expected.returns!.map(v=>v>0),[true,true,true]);
assert.deepEqual(evaluateQ102HighVolD126([...bars,{timestampMs:t,close:1e12}],t),expected,"No unfinished H1 read");
assert.deepEqual(evaluateQ102HighVolD126([...bars,{timestampMs:t+H,close:1e12}],t),expected,"No future read");
assert.equal(evaluateQ102HighVolD126(bars.map(b=>({...b,close:100})),t).status,"KEEP_SHORT","zero return is not positive");
assert.equal(evaluateQ102HighVolD126(bars.map((b,i)=>({...b,close:200-i})),t).status,"KEEP_SHORT");
assert.equal(evaluateQ102HighVolD126(bars.filter(b=>b.timestampMs!==t-25*H),t).status,"DATA_INVALID","Required daily candle missing");
assert.equal(evaluateQ102HighVolD126([...bars,bars[24]],t).status,"DATA_INVALID","Duplicate H1");
assert.equal(evaluateQ102HighVolD126(bars.map((b,i)=>i===23?{...b,close:NaN}:b),t).status,"DATA_INVALID");
assert.equal(evaluateQ102HighVolD126(bars,t+1).status,"DATA_INVALID","entry must be hourly");
assert.equal(quality102GrossForFamily("HIGH_VOL",-1),.6);
assert.equal(quality102GrossForFamily("HIGH_VOL",1),1);
console.log("QUALITY102_HIGHVOL_D126_SELFTEST_PASS");
