def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--candidates", type=Path, required=True)
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=Path("research_outputs/high_vol_scanner_forward_gate_v2"))
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)

    raw_candidates = json.loads(args.candidates.read_text(encoding="utf-8"))
    for row in raw_candidates:
        row["entry_time"] = pd.Timestamp(row["entry_time"])
        row["exit_time"] = pd.Timestamp(row["exit_time"])

    market, hourly_returns = load_market(args.cache)
    admitted, admission_rejected = eligible_candidates(raw_candidates)
    selected, portfolio_rejected = reserved_slot_selection(admitted, hourly_returns)

    pnl, equity = hv.simulate_hourly_portfolio(
        selected,
        market,
        notional_per_position=NOTIONAL_PER_SLOT,
        cost_per_side=0.0006,
        funding_per_day=0.0002,
    )
    stress_pnl, stress_equity = hv.simulate_hourly_portfolio(
        selected,
        market,
        notional_per_position=NOTIONAL_PER_SLOT,
        cost_per_side=0.0010,
        funding_per_day=0.0005,
    )

    payload = {
        "status": "RESEARCH_ONLY_DISABLED",
        "parameters": {
            "pengu_conditions_changed": False,
            "pengu_slot": NOTIONAL_PER_SLOT,
            "satellite_slot": NOTIONAL_PER_SLOT,
            "trailing_min_trades": TRAILING_MIN_TRADES,
            "trailing_min_win_rate": TRAILING_MIN_WIN_RATE,
            "trailing_min_profit_factor": TRAILING_MIN_PROFIT_FACTOR,
            "trailing_min_expectancy": TRAILING_MIN_EXPECTANCY,
            "forward_warmup_closed_trades": FORWARD_WARMUP_CLOSED_TRADES,
            "forward_min_win_rate": FORWARD_MIN_WIN_RATE,
            "forward_min_profit_factor": FORWARD_MIN_PROFIT_FACTOR,
            "correlation_cap": CORRELATION_CAP,
        },
        "counts": {
            "raw_candidates": len(raw_candidates),
            "admitted_candidates": len(admitted),
            "admission_rejected": len(admission_rejected),
            "selected_trades": len(selected),
            "portfolio_rejected": len(portfolio_rejected),
            "selected_by_symbol": dict(Counter(row["symbol"] for row in selected)),
            "admission_rejections": dict(Counter(row["admission_rejection"] for row in admission_rejected)),
            "portfolio_rejections": dict(Counter(
                "CORRELATED_WITH_ACTIVE_PENGU" if row["portfolio_rejection"].startswith("CORRELATED_WITH_ACTIVE_PENGU") else row["portfolio_rejection"]
                for row in portfolio_rejected
            )),
        },
        "recommended": {
            "hourly_mark_to_market": hv.portfolio_metrics(pnl, equity, selected),
            "exact_realized": exact_realized_metrics(selected),
            "hourly_stress": hv.portfolio_metrics(stress_pnl, stress_equity, selected),
        },
    }
    payload = core.json_safe(payload)

    (args.output / "summary.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    pd.DataFrame(selected).to_json(args.output / "selected_trades.json", orient="records", indent=2)
    pd.DataFrame(admission_rejected).to_json(args.output / "admission_rejected.json", orient="records", indent=2)
    pd.DataFrame(portfolio_rejected).to_json(args.output / "portfolio_rejected.json", orient="records", indent=2)
    pd.DataFrame({"pnl": pnl, "equity": equity}).to_csv(args.output / "equity.csv")
    pd.DataFrame({"pnl": stress_pnl, "equity": stress_equity}).to_csv(args.output / "equity_stress.csv")
    write_report(args.output / "REPORT.md", payload)

    print("HIGH_VOL_SCANNER_FORWARD_GATE_V2=" + json.dumps(payload, separators=(",", ":")))
    print((args.output / "REPORT.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
